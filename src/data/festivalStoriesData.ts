  if (key.includes('chhath')) return FESTIVAL_STORIES.chhath_puja;
  if (key.includes('shiv') || key.includes('mahashivratri')) return FESTIVAL_STORIES.shivratri;
  if (key.includes('krishna') || key.includes('janmashtami')) return FESTIVAL_STORIES.janmashtami;
  if (key.includes('ramnavami') || key.includes('ram_navami')) return FESTIVAL_STORIES.ramnavami;
